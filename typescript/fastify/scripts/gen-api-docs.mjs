// Generate docs/api-reference.md from the public @apipilot/fastify exports.
// Usage: node scripts/gen-api-docs.mjs > docs/api-reference.md

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const srcIndex = join(here, "..", "src", "index.ts");
const outPath = join(here, "..", "docs", "api-reference.md");

const src = readFileSync(srcIndex, "utf8");

// Collect exported names from `export { ... }` and `export const/function/class`.
const names = new Set();
for (const m of src.matchAll(/export\s*\{([^}]+)\}/g)) {
  for (const part of m[1].split(",")) {
    const name = part.trim().split(/\s+as\s+/).pop()?.trim();
    if (name && !name.startsWith("type ")) names.add(name);
  }
}
for (const m of src.matchAll(/export\s+(?:const|function|class|interface|type)\s+(\w+)/g)) {
  names.add(m[1]);
}

const sorted = [...names].sort();
const lines = [
  "# ApiPilot Fastify API reference",
  "",
  "Generated by `scripts/gen-api-docs.mjs` — do not edit by hand.",
  "",
  "## `@apipilot/fastify`",
  "",
];
for (const name of sorted) {
  lines.push(`- \`${name}\``);
}
lines.push("");

writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${outPath} (${sorted.length} exports)`);
