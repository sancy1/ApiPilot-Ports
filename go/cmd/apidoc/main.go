// Command apidoc generates Markdown API reference pages from Go doc
// comments. It is the Go equivalent of DocFX (C#), TypeDoc (TypeScript),
// and Sphinx (Python): doc comments are the single source of truth and
// the generated pages are build artifacts.
//
// Usage: go run ./cmd/apidoc [-out docs/api] [packages...]
//
// With no packages, it documents github.com/apipilot/go/core and
// github.com/apipilot/go/httpapi.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var defaultPkgs = []string{"core", "httpapi"}

func main() {
	out := flag.String("out", "docs/api", "output directory for generated Markdown")
	flag.Parse()

	pkgs := flag.Args()
	if len(pkgs) == 0 {
		pkgs = defaultPkgs
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		fatal(err)
	}

	for _, pkg := range pkgs {
		if err := genPackage(pkg, *out); err != nil {
			fatal(err)
		}
		fmt.Fprintf(os.Stderr, "apidoc: wrote %s.md\n", pkg)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "apidoc:", err)
	os.Exit(1)
}

// genPackage parses every non-test .go file in dir and writes one
// Markdown page documenting the package clause, package doc, and all
// exported declarations with their doc comments.
func genPackage(dir, out string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}

	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return fmt.Errorf("no Go files in %s", dir)
	}

	var b strings.Builder
	pkgName := files[0].Name.Name
	fmt.Fprintf(&b, "# Package %s\n\n", pkgName)
	fmt.Fprintf(&b, "<!-- Generated by `go run ./cmd/apidoc` — do not edit by hand. -->\n\n")

	// Package doc: the file whose doc comment starts with "Package ".
	for _, f := range files {
		if doc := docText(f.Doc); strings.HasPrefix(doc, "Package ") {
			b.WriteString(doc)
			b.WriteString("\n\n")
			break
		}
	}

	// Collect exported declarations across all files, sorted by name.
	type decl struct {
		kind string
		name string
		doc  string
		sig  string
	}
	var decls []decl

	for _, f := range files {
		for _, d := range f.Decls {
			switch n := d.(type) {
			case *ast.GenDecl:
				kind := strings.ToLower(n.Tok.String())
				for _, spec := range n.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						if !s.Name.IsExported() {
							continue
						}
						decls = append(decls, decl{
							kind: "type",
							name: s.Name.Name,
							doc:  docText(s.Doc),
							sig:  typeSignature(s),
						})
					case *ast.ValueSpec:
						for _, name := range s.Names {
							if !name.IsExported() {
								continue
							}
							decls = append(decls, decl{
								kind: kind,
								name: name.Name,
								doc:  docText(s.Doc),
							})
						}
					}
				}
			case *ast.FuncDecl:
				if n.Recv != nil || !n.Name.IsExported() {
					continue // methods documented under their type's section below
				}
				decls = append(decls, decl{
					kind: "func",
					name: n.Name.Name,
					doc:  docText(n.Doc),
					sig:  funcSignature(n),
				})
			}
		}
	}

	sort.Slice(decls, func(i, j int) bool {
		if decls[i].kind != decls[j].kind {
			return decls[i].kind < decls[j].kind
		}
		return decls[i].name < decls[j].name
	})

	for _, d := range decls {
		fmt.Fprintf(&b, "## %s %s\n\n", d.kind, d.name)
		if d.sig != "" {
			fmt.Fprintf(&b, "```go\n%s\n```\n\n", d.sig)
		}
		if d.doc != "" {
			b.WriteString(d.doc)
			b.WriteString("\n\n")
		}
	}

	return os.WriteFile(filepath.Join(out, pkgName+".md"), []byte(b.String()), 0o644)
}

// docText renders a comment group as plain text ("" when absent).
func docText(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	return strings.TrimSpace(g.Text())
}

// typeSignature renders a compact signature for a type declaration.
func typeSignature(s *ast.TypeSpec) string {
	switch t := s.Type.(type) {
	case *ast.StructType:
		return "type " + s.Name.Name + " struct { … }"
	case *ast.InterfaceType:
		return "type " + s.Name.Name + " interface { … }"
	default:
		return "type " + s.Name.Name + " " + exprSummary(t)
	}
}

// funcSignature renders "func Name(params) results" without bodies.
func funcSignature(n *ast.FuncDecl) string {
	var b strings.Builder
	b.WriteString("func ")
	b.WriteString(n.Name.Name)
	b.WriteString("(")
	if n.Type.Params != nil {
		for i, p := range n.Type.Params.List {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(exprSummary(p.Type))
		}
	}
	b.WriteString(")")
	if n.Type.Results != nil && len(n.Type.Results.List) > 0 {
		b.WriteString(" ")
		for i, r := range n.Type.Results.List {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(exprSummary(r.Type))
		}
	}
	return b.String()
}

// exprSummary renders a type expression as a short string.
func exprSummary(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return exprSummary(t.X) + "." + t.Sel.Name
	case *ast.StarExpr:
		return "*" + exprSummary(t.X)
	case *ast.ArrayType:
		return "[]" + exprSummary(t.Elt)
	case *ast.MapType:
		return "map[" + exprSummary(t.Key) + "]" + exprSummary(t.Value)
	case *ast.FuncType:
		return "func(…)"
	case *ast.InterfaceType:
		return "interface{…}"
	case *ast.StructType:
		return "struct{…}"
	case *ast.ChanType:
		return "chan " + exprSummary(t.Value)
	default:
		return "…"
	}
}
