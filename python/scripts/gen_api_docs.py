"""Generate docs/api-reference.md from the public apipilot API.

Usage: python scripts/gen_api_docs.py > docs/api-reference.md
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import apipilot
import apipilot.asgi


def _members(module) -> list[tuple[str, object]]:
    out = []
    for name in sorted(dir(module)):
        if name.startswith("_"):
            continue
        obj = getattr(module, name)
        if inspect.ismodule(obj):
            continue
        out.append((name, obj))
    return out


def _kind(obj) -> str:
    if inspect.isclass(obj):
        return "class"
    if inspect.isfunction(obj):
        return "function"
    return "value"


def _signature(obj) -> str:
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return ""


def _doc(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.splitlines()[0] if doc else ""


def render(module, title: str) -> str:
    lines = [f"## `{title}`", ""]
    for name, obj in _members(module):
        kind = _kind(obj)
        sig = _signature(obj)
        doc = _doc(obj)
        if kind == "class":
            lines.append(f"### class `{name}`")
        elif kind == "function":
            lines.append(f"### `{name}{sig}`")
        else:
            lines.append(f"### `{name}`")
        if doc:
            lines.append("")
            lines.append(doc)
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    print("# ApiPilot Python API reference")
    print("")
    print("Generated by `scripts/gen_api_docs.py` — do not edit by hand.")
    print("")
    # Core submodules carry the framework-neutral API.
    core_modules = [
        "content_negotiation",
        "cookie_profile",
        "correlation",
        "csrf_binding",
        "csrf_format",
        "envelope",
        "error_codes",
        "fetch_metadata",
        "field_key",
        "origin",
        "pagination",
    ]
    for mod_name in core_modules:
        mod = __import__(f"apipilot.{mod_name}", fromlist=["*"])
        print(render(mod, f"apipilot.{mod_name}"))
    print(render(apipilot.asgi, "apipilot.asgi"))


if __name__ == "__main__":
    main()
